import assert from 'node:assert/strict'
import { test } from 'node:test'

import { typograph } from '#/lib/typograph.ts'

// В ожиданиях неразрывный пробел записан точкой по центру: так видно, где он стоит.
const t = (text: string) => typograph(text).replaceAll(' ', '·')

test('короткие слова цепляются к следующему', () => {
	assert.equal(t('Я в Тольятти и онлайн'), 'Я·в·Тольятти и·онлайн')
	assert.equal(t('Подготовка для встречи'), 'Подготовка для·встречи')
})

test('частицы держатся за предыдущее слово', () => {
	assert.equal(t('Пришла бы ли она'), 'Пришла·бы·ли она')
})

test('числа: единицы, разряды, годы', () => {
	assert.equal(t('Стоит 2499 ₽ за 60 минут'), 'Стоит 2499·₽ за·60·минут')
	assert.equal(t('Было 12000 человек в 2024 году'), 'Было 12·000·человек в·2024·году')
	assert.equal(t('Это 2 499 рублей'), 'Это 2·499·рублей')
})

test('телефон остаётся целым, разряды в нём не трогаются', () => {
	assert.equal(t('Звоните +7 (900) 123-45-67 в любой день'), 'Звоните +7·(900)·123-45-67 в·любой день')
	assert.equal(t('Звонок на 8 800 2000 122'), 'Звонок на·8·800·2000·122')
})

test('сокращения, инициалы, тире, многоточие', () => {
	assert.equal(t('т. е. всё'), 'т.·е. всё')
	assert.equal(t('А. С. Пушкин'), 'А.·С.·Пушкин')
	assert.equal(t('Тревога — это нормально'), 'Тревога·— это нормально')
	assert.equal(t('Ну... ладно'), 'Ну… ладно')
})
